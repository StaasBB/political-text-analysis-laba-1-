from summa.keywords import keywords

text = """
Государство есть организация насилия одного класса над другим.
Всякая власть служит интересам имущих. Рабочий класс должен взять
власть в свои руки и установить свою диктатуру. Только так, через
революционное насилие, через слом старой государственной машины,
человечество придёт к подлинному освобождению.
"""

result = keywords(
    text,
    words=10,
    language="russian",
    split=True,
    scores=True,
)
print(result)